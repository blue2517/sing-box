# Hysteria2 增强管理模块：Salamander 混淆、自定义证书、伪装站与 UDP 端口跳跃

is_hy2_hop_conf="$is_core_dir/hy2-hopping.conf"
is_hy2_hop_script="$is_core_dir/hy2-port-hopping.sh"
is_hy2_systemd_dropin_dir="/etc/systemd/system/${is_core}.service.d"
is_hy2_systemd_dropin="$is_hy2_systemd_dropin_dir/hy2-hopping.conf"

hy2_get_hopping_range() {
    local target_port=$1
    [[ ! -f $is_hy2_hop_conf || -z $target_port ]] && return
    awk -F: -v p="$target_port" '$1 == p {print $2 "-" $3; exit}' "$is_hy2_hop_conf"
}

_hy2_require_inbound() {
    is_dont_show_info=1
    get info "$1"
    is_dont_show_info=
    [[ $is_protocol != "hysteria2" ]] && err "($is_config_file) 不是 Hysteria2 配置."
}

_hy2_write_hop_script() {
    cat >"$is_hy2_hop_script" <<EOF
#!/bin/bash
# Auto-generated by sing-box script for Hysteria2 UDP port hopping

HOP_CONF="$is_hy2_hop_conf"
CHAIN="SB_HY2_HOPPING"

get_default_iface() {
    local family=\$1
    ip -\$family route show default 2>/dev/null | awk '/default/ {for (i=1;i<=NF;i++) if (\$i=="dev") {print \$(i+1); exit}}'
}

clear_chain() {
    local tool=\$1
    local iface=\$2
    command -v "\$tool" &>/dev/null || return 0
    if [[ -n \$iface ]]; then
        while "\$tool" -t nat -C PREROUTING -i "\$iface" -j "\$CHAIN" 2>/dev/null; do
            "\$tool" -t nat -D PREROUTING -i "\$iface" -j "\$CHAIN" 2>/dev/null || break
        done
    fi
    while "\$tool" -t nat -S PREROUTING 2>/dev/null | grep -q " -j \$CHAIN\$"; do
        local rule
        rule=\$("\$tool" -t nat -S PREROUTING 2>/dev/null | grep " -j \$CHAIN\$" | head -n1 | sed 's/^-A /-D /')
        [[ -n \$rule ]] && "\$tool" -t nat \$rule 2>/dev/null || break
    done
    "\$tool" -t nat -F "\$CHAIN" 2>/dev/null || true
    "\$tool" -t nat -X "\$CHAIN" 2>/dev/null || true
}

start_hopping() {
    [[ ! -s \$HOP_CONF ]] && return 0
    local iface4 iface6
    iface4=\$(get_default_iface 4)
    iface6=\$(get_default_iface 6)

    for tool_iface in "iptables:\$iface4" "ip6tables:\$iface6"; do
        local tool=\${tool_iface%%:*}
        local iface=\${tool_iface#*:}
        command -v "\$tool" &>/dev/null || continue
        [[ -z \$iface ]] && continue
        clear_chain "\$tool" "\$iface"
        "\$tool" -t nat -N "\$CHAIN" 2>/dev/null || true
        while IFS=: read -r target_port start_port end_port _cfg; do
            [[ -z \$target_port || \$target_port == \#* ]] && continue
            "\$tool" -t nat -A "\$CHAIN" -p udp --dport "\${start_port}:\${end_port}" -j REDIRECT --to-ports "\$target_port"
        done < "\$HOP_CONF"
        "\$tool" -t nat -A PREROUTING -i "\$iface" -j "\$CHAIN"
    done
}

stop_hopping() {
    clear_chain iptables "\$(get_default_iface 4)"
    clear_chain ip6tables "\$(get_default_iface 6)"
}

case "\$1" in
start)
    start_hopping
    ;;
stop)
    stop_hopping
    ;;
restart)
    stop_hopping
    start_hopping
    ;;
*)
    echo "Usage: \$0 {start|stop|restart}"
    exit 1
    ;;
esac
EOF
    chmod +x "$is_hy2_hop_script"
}

_hy2_sync_service_hook() {
    if [[ -s $is_hy2_hop_conf ]]; then
        _hy2_write_hop_script
        if [[ $is_systemd ]]; then
            mkdir -p "$is_hy2_systemd_dropin_dir"
            cat >"$is_hy2_systemd_dropin" <<EOF
[Service]
ExecStartPost=$is_hy2_hop_script start
ExecStopPost=$is_hy2_hop_script stop
EOF
            systemctl daemon-reload 2>/dev/null || true
        fi
        "$is_hy2_hop_script" restart
    else
        [[ -x $is_hy2_hop_script ]] && "$is_hy2_hop_script" stop 2>/dev/null || true
        rm -f "$is_hy2_hop_conf" "$is_hy2_hop_script" "$is_hy2_systemd_dropin"
        rmdir "$is_hy2_systemd_dropin_dir" 2>/dev/null || true
        [[ $is_systemd ]] && systemctl daemon-reload 2>/dev/null || true
    fi
}

hy2_update_hopping_port() {
    local old_port=$1 new_port=$2 cfg_name=$3
    [[ ! -f $is_hy2_hop_conf ]] && return 0
    local range
    range=$(hy2_get_hopping_range "$old_port")
    [[ -z $range ]] && return 0
    local start_p=${range%-*} end_p=${range#*-}
    local tmp_conf
    tmp_conf=$(awk -F: -v p="$old_port" '$1 != p {print}' "$is_hy2_hop_conf")
    if [[ -n $new_port ]]; then
        tmp_conf="${tmp_conf:+$tmp_conf$'\n'}${new_port}:${start_p}:${end_p}:${cfg_name}"
    fi
    if [[ -n $tmp_conf ]]; then
        printf '%s\n' "$tmp_conf" >"$is_hy2_hop_conf"
    else
        : >"$is_hy2_hop_conf"
    fi
    _hy2_sync_service_hook
}

hy2_remove_hopping_by_port() {
    hy2_update_hopping_port "$1" "" ""
}

hy2_set_obfs() {
    _hy2_require_inbound "$1"
    local obfs_pass=$2
    [[ ! $obfs_pass ]] && ask string obfs_pass "请输入 Salamander 混淆密码 (输入 auto 随机生成, off 关闭):"

    local target_file="$is_conf_dir/$is_config_file"
    local backup_file
    backup_file=$(mktemp)
    cp -pf "$target_file" "$backup_file"

    local new_json
    case ${obfs_pass,,} in
    off | none | clear)
        new_json=$(jq 'del(.inbounds[0].obfs)' "$target_file") || { rm -f "$backup_file"; err "更新混淆配置失败."; }
        msg "\n已关闭 ($is_config_file) 的 Salamander 混淆."
        ;;
    *)
        if [[ ${obfs_pass,,} == "auto" ]]; then
            obfs_pass=$(tr -dc 'A-Za-z0-9_-' </dev/urandom | head -c 32)
        fi
        new_json=$(jq --arg p "$obfs_pass" '.inbounds[0].obfs = {type: "salamander", password: $p}' "$target_file") || { rm -f "$backup_file"; err "更新混淆配置失败."; }
        msg "\n已设置 ($is_config_file) 的 Salamander 混淆密码: $(_green "$obfs_pass")"
        ;;
    esac

    _commit_config_json "$target_file" "$new_json" "$backup_file" 600
    manage restart &
    is_protocol=
    info "$is_config_file"
}

hy2_set_cert() {
    _hy2_require_inbound "$1"
    local cert_path=$2 key_path=$3 sni=$4
    if [[ ! $cert_path ]]; then
        msg "\n常见证书路径提示:"
        msg "  - Let's Encrypt: /etc/letsencrypt/live/<域名>/fullchain.pem & privkey.pem"
        msg "  - 独立 Hysteria/同步: /etc/hysteria/cert.crt & /etc/hysteria/cert.key"
        msg "  - 恢复默认自签名: 输入 self"
        ask string cert_path "请输入证书路径 (.crt/.pem) 或 self:"
    fi

    local target_file="$is_conf_dir/$is_config_file"
    local backup_file
    backup_file=$(mktemp)
    cp -pf "$target_file" "$backup_file"

    local new_json
    if [[ ${cert_path,,} == "self" || ${cert_path,,} == "auto" ]]; then
        ensure_default_tls_pair
        new_json=$(jq --arg c "$is_core_dir/bin/tls.cer" --arg k "$is_core_dir/bin/tls.key" '
          .inbounds[0].tls.certificate_path = $c |
          .inbounds[0].tls.key_path = $k |
          del(.inbounds[0].tls.server_name)
        ' "$target_file") || { rm -f "$backup_file"; err "恢复自签名证书失败."; }
    else
        [[ ! -f $cert_path ]] && { rm -f "$backup_file"; err "找不到证书文件: $cert_path"; }
        [[ ! $key_path ]] && ask string key_path "请输入私钥路径 (.key):"
        [[ ! -f $key_path ]] && { rm -f "$backup_file"; err "找不到私钥文件: $key_path"; }
        if [[ ! $sni ]] && command -v openssl &>/dev/null; then
            sni=$(openssl x509 -noout -ext subjectAltName -in "$cert_path" 2>/dev/null | grep -oE 'DNS:[^, ]+' | head -n1 | sed 's/^DNS://')
            [[ ! $sni ]] && sni=$(openssl x509 -noout -subject -nameopt RFC2253 -in "$cert_path" 2>/dev/null | sed -n 's/.*CN=\([^,]*\).*/\1/p')
        fi
        [[ ! $sni ]] && ask string sni "请输入证书对应域名 (SNI):"
        new_json=$(jq --arg c "$cert_path" --arg k "$key_path" --arg sni "$sni" '
          .inbounds[0].tls.certificate_path = $c |
          .inbounds[0].tls.key_path = $k |
          if ($sni | length) > 0 then .inbounds[0].tls.server_name = $sni else del(.inbounds[0].tls.server_name) end
        ' "$target_file") || { rm -f "$backup_file"; err "设置自定义证书失败."; }
    fi

    _commit_config_json "$target_file" "$new_json" "$backup_file"
    manage restart &
    is_protocol=
    info "$is_config_file"
}

hy2_set_web() {
    _hy2_require_inbound "$1"
    local web_url=$2
    [[ ! $web_url ]] && ask string web_url "请输入伪装网站 URL (例如 https://guizi.asia/ 或 off 关闭):"

    local target_file="$is_conf_dir/$is_config_file"
    local backup_file
    backup_file=$(mktemp)
    cp -pf "$target_file" "$backup_file"

    local new_json
    case ${web_url,,} in
    off | none | clear)
        new_json=$(jq 'del(.inbounds[0].masquerade)' "$target_file") || { rm -f "$backup_file"; err "清除伪装网站失败."; }
        ;;
    *)
        [[ ! $web_url =~ ^https?:// ]] && web_url="https://${web_url}"
        new_json=$(jq --arg u "$web_url" '.inbounds[0].masquerade = $u' "$target_file") || { rm -f "$backup_file"; err "设置伪装网站失败."; }
        ;;
    esac

    _commit_config_json "$target_file" "$new_json" "$backup_file"
    manage restart &
    is_protocol=
    info "$is_config_file"
}

hy2_set_hop() {
    _hy2_require_inbound "$1"
    local range=$2
    [[ ! $range ]] && ask string range "请输入 UDP 跳跃端口范围 (格式 start-end 如 20000-20099, 或 off 关闭):"

    case ${range,,} in
    off | none | clear)
        hy2_remove_hopping_by_port "$port"
        msg "\n已关闭 ($is_config_file) 的 UDP 端口跳跃.\n"
        ;;
    *)
        if [[ ! $range =~ ^([0-9]+)-([0-9]+)$ ]]; then
            err "端口范围格式错误: $range (正确格式如: 20000-20099)"
        fi
        local start_p=${BASH_REMATCH[1]} end_p=${BASH_REMATCH[2]}
        if (( start_p < 1 || end_p > 65535 || start_p >= end_p )); then
            err "无效端口范围: $start_p-$end_p (要求 1 <= start < end <= 65535)"
        fi
        if (( port >= start_p && port <= end_p )); then
            err "跳跃端口范围 ($start_p-$end_p) 不能包含 Hysteria2 监听端口 ($port)."
        fi
        mkdir -p "$is_core_dir"
        local tmp_conf=""
        if [[ -f $is_hy2_hop_conf ]]; then
            tmp_conf=$(awk -F: -v p="$port" '$1 != p {print}' "$is_hy2_hop_conf")
        fi
        tmp_conf="${tmp_conf:+$tmp_conf$'\n'}${port}:${start_p}:${end_p}:${is_config_file}"
        printf '%s\n' "$tmp_conf" >"$is_hy2_hop_conf"
        _hy2_sync_service_hook
        msg "\n已启用 UDP 端口跳跃: $(_green "${start_p}-${end_p}/udp -> ${port}/udp")\n"
        ;;
    esac
    is_protocol=
    info "$is_config_file"
}
